#!/usr/bin/env node
/**
 * Development Startup Script
 * Starts Hardhat node, deploys contract, updates config, and runs backend + frontend
 */

const { spawn, execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const http = require('http');

const colors = {
  reset: '\x1b[0m',
  bright: '\x1b[1m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  blue: '\x1b[34m',
  red: '\x1b[31m',
  cyan: '\x1b[36m'
};

function log(message, color = 'reset') {
  console.log(`${colors[color]}${message}${colors.reset}`);
}

function logSection(title) {
  console.log('\n' + '='.repeat(60));
  log(title, 'bright');
  console.log('='.repeat(60) + '\n');
}

// Check if Hardhat node is ready
async function waitForHardhatNode(maxAttempts = 30) {
  log('Waiting for Hardhat node to start...', 'yellow');
  
  for (let i = 0; i < maxAttempts; i++) {
    try {
      const response = await new Promise((resolve, reject) => {
        const req = http.request({
          hostname: '127.0.0.1',
          port: 8545,
          path: '/',
          method: 'POST',
          headers: {
            'Content-Type': 'application/json'
          }
        }, (res) => {
          resolve(true);
        });
        
        req.on('error', () => resolve(false));
        req.write(JSON.stringify({ jsonrpc: '2.0', method: 'eth_blockNumber', params: [], id: 1 }));
        req.end();
      });
      
      if (response) {
        log('Hardhat node is ready!', 'green');
        return true;
      }
    } catch (e) {
      // Node not ready yet
    }
    
    process.stdout.write('.');
    await new Promise(r => setTimeout(r, 1000));
  }
  
  log('\nHardhat node failed to start within timeout', 'red');
  return false;
}

// Deploy contract and get address
async function deployContract() {
  logSection('STEP 2: Deploying Smart Contract');
  
  try {
    const result = execSync('npx hardhat run scripts/deploy-local.js --network localhost', {
      encoding: 'utf8',
      cwd: path.join(__dirname, '..'),
      stdio: 'pipe'
    });
    
    console.log(result);
    
    // Extract contract address from output
    const match = result.match(/deployed to: (0x[a-fA-F0-9]{40})/);
    if (match) {
      const contractAddress = match[1];
      log(`Contract deployed at: ${contractAddress}`, 'green');
      return contractAddress;
    }
    
    // Try to read from deployment.json
    const deploymentPath = path.join(__dirname, '..', 'deployment.json');
    if (fs.existsSync(deploymentPath)) {
      const deployment = JSON.parse(fs.readFileSync(deploymentPath, 'utf8'));
      if (deployment.contractAddress) {
        log(`Contract found in deployment.json: ${deployment.contractAddress}`, 'green');
        return deployment.contractAddress;
      }
    }
    
    throw new Error('Could not find contract address in deployment output');
  } catch (error) {
    log('Contract deployment failed:', 'red');
    log(error.message, 'red');
    throw error;
  }
}

// Update frontend .env.local with contract address
function updateFrontendEnv(contractAddress) {
  logSection('STEP 3: Updating Frontend Configuration');
  
  const envPath = path.join(__dirname, '..', 'frontend', '.env.local');
  const envContent = `# Auto-generated by start-dev.js
VITE_CONTRACT_ADDRESS=${contractAddress}
`;
  
  fs.writeFileSync(envPath, envContent);
  log(`Updated ${envPath} with contract address`, 'green');
  log(`VITE_CONTRACT_ADDRESS=${contractAddress}`, 'cyan');
}

// Start Hardhat node
function startHardhatNode() {
  logSection('STEP 1: Starting Hardhat Local Node');
  
  const hardhatProcess = spawn('npx', ['hardhat', 'node'], {
    cwd: path.join(__dirname, '..'),
    stdio: 'inherit',
    shell: true,
    windowsHide: false
  });
  
  hardhatProcess.on('error', (err) => {
    log(`Failed to start Hardhat node: ${err.message}`, 'red');
    process.exit(1);
  });
  
  return hardhatProcess;
}

// Start backend and frontend in parallel
function startBackendAndFrontend() {
  logSection('STEP 4: Starting Backend and Frontend');
  
  const concurrentlyPath = path.join(__dirname, '..', 'node_modules', '.bin', 'concurrently');
  
  const args = [
    '--names', 'BACKEND,FRONTEND',
    '--prefix-colors', 'bgBlue.bold,bgGreen.bold',
    '--kill-others-on-fail',
    '--restart-tries', '1',
    'cd backend && npm run dev',
    'cd frontend && npm run dev'
  ];
  
  const processes = spawn(concurrentlyPath, args, {
    cwd: path.join(__dirname, '..'),
    stdio: 'inherit',
    shell: true,
    windowsHide: false
  });
  
  return processes;
}

// Main execution
async function main() {
  logSection('🚀 Blockchain Voting System - Development Mode');
  log('Starting all services...', 'bright');
  
  let hardhatProcess = null;
  let servicesProcess = null;
  
  try {
    // Step 1: Start Hardhat node
    hardhatProcess = startHardhatNode();
    
    // Wait for node to be ready
    const nodeReady = await waitForHardhatNode();
    if (!nodeReady) {
      throw new Error('Hardhat node failed to start');
    }
    
    // Step 2: Deploy contract
    const contractAddress = await deployContract();
    
    // Step 3: Update frontend config
    updateFrontendEnv(contractAddress);
    
    // Step 4: Start backend and frontend
    servicesProcess = startBackendAndFrontend();
    
    // Handle graceful shutdown
    const cleanup = () => {
      log('\n\nShutting down services...', 'yellow');
      
      if (servicesProcess) {
        servicesProcess.kill('SIGTERM');
      }
      if (hardhatProcess) {
        hardhatProcess.kill('SIGTERM');
      }
      
      setTimeout(() => {
        log('Cleanup complete', 'green');
        process.exit(0);
      }, 2000);
    };
    
    process.on('SIGINT', cleanup);
    process.on('SIGTERM', cleanup);
    process.on('exit', cleanup);
    
    // Keep the script running
    await new Promise(() => {});
    
  } catch (error) {
    log(`\n❌ Startup failed: ${error.message}`, 'red');
    
    if (hardhatProcess) hardhatProcess.kill();
    if (servicesProcess) servicesProcess.kill();
    
    process.exit(1);
  }
}

// Run if called directly
if (require.main === module) {
  main().catch(console.error);
}

module.exports = { main, waitForHardhatNode, deployContract };
