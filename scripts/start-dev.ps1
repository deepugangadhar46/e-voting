# Development Startup Script for Windows PowerShell
# Starts Hardhat node, deploys contract, updates config, and runs backend + frontend

$ErrorActionPreference = "Stop"

# Colors for output
function Write-ColorOutput($message, $color = "White") {
    Write-Host $message -ForegroundColor $color
}

function Write-Section($title) {
    Write-Host "`n$('=' * 60)" -ForegroundColor Cyan
    Write-ColorOutput $title "Yellow"
    Write-Host "$('=' * 60)`n" -ForegroundColor Cyan
}

# Get project root
$projectRoot = Split-Path -Parent $PSScriptRoot
Set-Location $projectRoot

Write-Section "🚀 Blockchain Voting System - Development Mode"
Write-ColorOutput "Starting all services..." "Yellow"

# Step 1: Start Hardhat Node in background
Write-Section "STEP 1: Starting Hardhat Local Node"

$hardhatJob = Start-Job -ScriptBlock {
    Set-Location $using:projectRoot
    npx hardhat node 2>&1
} -Name "HardhatNode"

Write-ColorOutput "Hardhat node starting in background (Job ID: $($hardhatJob.Id))" "Green"

# Wait for node to be ready
Write-ColorOutput "Waiting for Hardhat node to be ready..." "Yellow"
$maxAttempts = 30
$ready = $false

for ($i = 0; $i -lt $maxAttempts; $i++) {
    Start-Sleep -Seconds 1
    
    try {
        $response = Invoke-WebRequest -Uri "http://127.0.0.1:8545" -Method POST `
            -Body '{"jsonrpc":"2.0","method":"eth_blockNumber","params":[],"id":1}' `
            -ContentType "application/json" -UseBasicParsing -TimeoutSec 2 -ErrorAction Stop
        
        if ($response.StatusCode -eq 200) {
            $ready = $true
            Write-ColorOutput "Hardhat node is ready!" "Green"
            break
        }
    }
    catch {
        Write-Host "." -NoNewline -ForegroundColor Yellow
    }
}

if (-not $ready) {
    Write-ColorOutput "`nHardhat node failed to start within timeout" "Red"
    Stop-Job $hardhatJob
    exit 1
}

# Step 2: Deploy Contract
Write-Section "STEP 2: Deploying Smart Contract"

try {
    $deployOutput = npx hardhat run scripts/deploy-local.js --network localhost 2>&1
    Write-Output $deployOutput
    
    # Extract contract address
    $contractMatch = $deployOutput | Select-String -Pattern "deployed to: (0x[a-fA-F0-9]{40})"
    if ($contractMatch) {
        $contractAddress = $contractMatch.Matches.Groups[1].Value
        Write-ColorOutput "Contract deployed at: $contractAddress" "Green"
    }
    else {
        # Try reading from deployment.json
        $deploymentPath = Join-Path $projectRoot "deployment.json"
        if (Test-Path $deploymentPath) {
            $deployment = Get-Content $deploymentPath | ConvertFrom-Json
            $contractAddress = $deployment.contractAddress
            Write-ColorOutput "Contract found in deployment.json: $contractAddress" "Green"
        }
        else {
            throw "Could not find contract address"
        }
    }
}
catch {
    Write-ColorOutput "Contract deployment failed: $_" "Red"
    Stop-Job $hardhatJob
    exit 1
}

# Step 3: Update Frontend Config
Write-Section "STEP 3: Updating Frontend Configuration"

$envPath = Join-Path $projectRoot "frontend" ".env.local"
$envContent = @"
# Auto-generated by start-dev.ps1
VITE_CONTRACT_ADDRESS=$contractAddress
"@

$envContent | Out-File -FilePath $envPath -Encoding utf8 -Force
Write-ColorOutput "Updated $envPath with contract address" "Green"
Write-ColorOutput "VITE_CONTRACT_ADDRESS=$contractAddress" "Cyan"

# Step 4: Start Backend and Frontend
Write-Section "STEP 4: Starting Backend and Frontend"

$backendJob = Start-Job -ScriptBlock {
    Set-Location (Join-Path $using:projectRoot "backend")
    npm run dev 2>&1
} -Name "Backend"

$frontendJob = Start-Job -ScriptBlock {
    Set-Location (Join-Path $using:projectRoot "frontend")
    npm run dev 2>&1
} -Name "Frontend"

Write-ColorOutput "Backend started (Job ID: $($backendJob.Id))" "Blue"
Write-ColorOutput "Frontend started (Job ID: $($frontendJob.Id))" "Green"
Write-Host ""

# Display summary
Write-Section "✅ All Services Started Successfully!"
Write-ColorOutput "Services running:" "Yellow"
Write-ColorOutput "  • Hardhat Node:    http://127.0.0.1:8545" "Green"
Write-ColorOutput "  • Backend API:     http://localhost:5000" "Blue"
Write-ColorOutput "  • Frontend App:    http://localhost:3000" "Magenta"
Write-ColorOutput "  • Contract:        $contractAddress" "Cyan"
Write-Host ""
Write-ColorOutput "Press Ctrl+C to stop all services" "Yellow"

# Monitor jobs and display output
try {
    while ($true) {
        $jobs = Get-Job | Where-Object { $_.Name -in @("HardhatNode", "Backend", "Frontend") }
        
        foreach ($job in $jobs) {
            if ($job.State -eq "Failed") {
                Write-ColorOutput "Job $($job.Name) failed!" "Red"
                Receive-Job $job
                throw "Service crashed"
            }
            
            $output = Receive-Job $job -Keep
            if ($output) {
                $prefix = switch ($job.Name) {
                    "HardhatNode" { "[HARDHAT]" }
                    "Backend"     { "[BACKEND]" }
                    "Frontend"    { "[FRONTEND]" }
                }
                $color = switch ($job.Name) {
                    "HardhatNode" { "Gray" }
                    "Backend"     { "Blue" }
                    "Frontend"    { "Green" }
                }
                Write-ColorOutput "$prefix $($output -join "`n$prefix ")" $color
            }
        }
        
        Start-Sleep -Milliseconds 100
    }
}
catch {
    Write-ColorOutput "`n`nShutting down services..." "Yellow"
}
finally {
    # Cleanup
    Get-Job | Where-Object { $_.Name -in @("HardhatNode", "Backend", "Frontend") } | Stop-Job
    Get-Job | Where-Object { $_.Name -in @("HardhatNode", "Backend", "Frontend") } | Remove-Job
    Write-ColorOutput "All services stopped" "Green"
}
